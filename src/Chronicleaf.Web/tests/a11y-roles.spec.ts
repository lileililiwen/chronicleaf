import { expect, test, type Page } from '@playwright/test';

/**
 * WEB-A11Y-ROLES-001/002/003/004/005 in a real browser, against the real
 * published application with a real PostgreSQL behind it.
 *
 * This suite runs in its own e2e group with its own disposable database
 * (see scripts/e2e.sh, suite 29): it creates projects and confirmed
 * milestones by clicking, and a project cannot be removed once it
 * exists, so it reads its own installation rather than the one suite 1
 * asserts empty. Every record below is created by the same clicks an
 * owner would make, with names unique to this suite, and every claim is
 * read back from the page. No capture carries a credential, a token, a
 * PAT or a session value.
 *
 * The setup token is generated by scripts/e2e.sh for this run and handed
 * to the fixtures through the environment. It is never written into this
 * file, never printed and never asserted on.
 */
const ACCESS_TOKEN = process.env.CHRONICLEAF_E2E_ACCESS_TOKEN;

test.beforeEach(async ({ page }) => {
  if (!ACCESS_TOKEN) {
    throw new Error(
      'CHRONICLEAF_E2E_ACCESS_TOKEN is not set. Run these fixtures through scripts/e2e.sh, which ' +
        'starts the published application with a real access token hash and a real database.',
    );
  }

  await page.context().clearCookies();
  await page.goto('/');
});


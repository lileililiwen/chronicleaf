import { expect, test } from '@playwright/test';

/**
 * PRODUCT-SHELL-UX-001/002/003/004 in a real browser, against the real
 * published application with a real PostgreSQL behind it.
 *
 * This suite runs in the first e2e group (see scripts/e2e.sh), which also
 * asserts that a new installation starts empty — so nothing here creates a
 * project, a milestone, a credential or any other record. Every capture is
 * an empty/generic state, and no capture carries a credential, a token, a
 * PAT or a session value: the settings shots assert the labelled session
 * facts, never a raw identity.
 *
 * The setup token is generated by scripts/e2e.sh for this run and handed to
 * the fixtures through the environment. It is never written into this file,
 * never printed and never asserted on.
 */
const ACCESS_TOKEN = process.env.CHRONICLEAF_E2E_ACCESS_TOKEN;

const NAV = [
  { testid: 'nav-projects', heading: 'Dashboard', headingTestid: null as string | null },
  { testid: 'nav-timeline', heading: 'Timeline', headingTestid: 'timeline-page-heading' },
  { testid: 'nav-operations', heading: 'Background jobs', headingTestid: null as string | null },
  { testid: 'nav-credentials', heading: 'Provider credentials', headingTestid: null as string | null },
  { testid: 'nav-settings', heading: 'Settings', headingTestid: 'settings-heading' },
] as const;

const FORBIDDEN = [
  'NOT IN THIS CHANGE',
  'Not in this change',
  'Project setup coming in a later change.',
];

test.beforeEach(async ({ page }) => {
  if (!ACCESS_TOKEN) {
    throw new Error(
      'CHRONICLEAF_E2E_ACCESS_TOKEN is not set. Run these fixtures through scripts/e2e.sh, which ' +
        'starts the published application with a real access token hash and a real database.',
    );
  }

  await page.context().clearCookies();
  await page.goto('/');
  await signInFromTheKeyboard(page);
});

test('every product area is one nav step away from every other', async ({ page }) => {
  for (const from of NAV) {
    await page.getByTestId(from.testid).click();

    for (const to of NAV) {
      // No back-link is used: each destination is reached from the nav itself.
      await page.getByTestId(to.testid).click();
      await expectHeading(page, to);
      await expect(page.getByTestId(to.testid)).toHaveAttribute('aria-current', 'page');
    }
  }
});

test('each product page shows its own h1 and no repeated global header', async ({ page }) => {
  for (const entry of NAV) {
    await page.getByTestId(entry.testid).click();
    await expectHeading(page, entry);

    const h1Count = await page.locator('h1').count();
    expect(h1Count, `exactly one h1 on ${entry.testid}`).toBe(1);

    // The shell brand is a nav control, not a repeated heading.
    await expect(page.getByRole('heading', { name: 'Chronicleaf', exact: true })).toHaveCount(0);
    await expect(page.getByTestId('brand-home')).toBeVisible();
  }
});

test('the brand mark returns to the dashboard from every product area', async ({ page }) => {
  for (const entry of NAV) {
    await page.getByTestId(entry.testid).click();
    await page.getByTestId('brand-home').click();
    await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible();
  }
});

test('session internals render only under settings', async ({ page }) => {
  const productPages = ['nav-projects', 'nav-timeline', 'nav-operations', 'nav-credentials'] as const;

  for (const testid of productPages) {
    await page.getByTestId(testid).click();
    const body = (await page.getByTestId('app-shell').textContent()) ?? '';

    expect(body, `${testid} shows no idle timeout`).not.toContain('Idle timeout');
    expect(body, `${testid} shows no session lifetime`).not.toContain('Session lifetime');
    expect(body, `${testid} shows no actor identity`).not.toContain('Actor');
    expect(body, `${testid} shows no UUID`).not.toMatch(
      /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i,
    );
  }

  await page.getByTestId('nav-settings').click();
  await expect(page.getByTestId('settings-session-facts')).toBeVisible();
  await expect(page.getByTestId('settings-idle')).toContainText('12 hours');
  await expect(page.getByTestId('settings-lifetime')).toContainText('7 days');

  // The actor renders as a label, never as a raw UUID dump.
  await expect(page.getByTestId('settings-actor')).toContainText("This installation's owner");
  const settingsBody = (await page.getByTestId('settings').textContent()) ?? '';
  expect(settingsBody).not.toMatch(
    /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i,
  );
});

test('the settings page links on to credentials and nothing else', async ({ page }) => {
  await page.getByTestId('nav-settings').click();
  await page.getByTestId('settings-credentials-link').click();
  await expect(
    page.getByRole('heading', { name: 'Provider credentials', exact: true }),
  ).toBeVisible();
});

test('no product page renders authoring scaffolding', async ({ page }) => {
  for (const entry of NAV) {
    await page.getByTestId(entry.testid).click();
    const body = (await page.getByTestId('app-shell').textContent()) ?? '';

    for (const forbidden of FORBIDDEN) {
      expect(body, `${entry.testid} renders no scaffolding`).not.toContain(forbidden);
    }

    await expect(page.getByTestId('setup-pending')).toHaveCount(0);
    await expect(page.getByTestId('later-packages')).toHaveCount(0);
  }
});

test('an unknown path stays inside the shell with its nav intact', async ({ page }) => {
  await page.goto('/no-such-place');
  await expect(page.getByTestId('app-nav')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Nothing here', exact: true })).toBeVisible();
  await expect(page.getByTestId('route-home')).toBeVisible();

  // And the nav still moves from there.
  await page.getByTestId('nav-operations').click();
  await expect(page.getByRole('heading', { name: 'Background jobs', exact: true })).toBeVisible();
});

test('DELTA captures: one empty-state screenshot per nav entry', async ({ page }) => {
  for (const entry of NAV) {
    await page.getByTestId(entry.testid).click();
    await expectHeading(page, entry);
    await expectSettled(page, entry.testid);
    await page.screenshot({ path: `test-results/delta/${entry.testid}.png` });
  }

  // The project-new form is not a nav entry but is a named DELTA surface: it
  // renders empty and nothing here submits it, so the installation stays empty.
  await page.goto('/projects/new');
  await expect(page.getByRole('heading', { name: 'New project', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/delta/project-new.png' });
});

/** Asserts the entry's own h1, by testid where the name is shared with an embedded section. */
async function expectHeading(page: import('@playwright/test').Page, entry: (typeof NAV)[number]) {
  if (entry.headingTestid !== null) {
    await expect(page.getByTestId(entry.headingTestid)).toHaveText(entry.heading);
  } else {
    await expect(page.getByRole('heading', { name: entry.heading, exact: true })).toBeVisible();
  }
}

/**
 * Waits until the entry's own content has settled, so a DELTA capture shows
 * the rendered state rather than a loading flash. Either branch of each
 * empty-or-list pair is a settled render.
 */
async function expectSettled(page: import('@playwright/test').Page, testid: string) {
  switch (testid) {
    case 'nav-projects':
      await expect(
        page.getByTestId('dashboard-empty').or(page.getByTestId('dashboard-projects')),
      ).toBeVisible();
      break;
    case 'nav-timeline':
      await expect(
        page.getByTestId('timeline-empty').or(page.getByTestId('timeline-picker')),
      ).toBeVisible();
      break;
    case 'nav-operations':
      await expect(
        page.getByTestId('operations-empty').or(page.getByTestId('operations-list')),
      ).toBeVisible();
      break;
    case 'nav-credentials':
      // The provider rows render first as "Reading"; the capture waits until
      // the first row's read has landed and the save control is decidable.
      await expect(page.getByTestId('credential-github-unknown')).toHaveCount(0);
      await expect(page.getByTestId('credential-vault-providers')).toBeVisible();
      break;
    case 'nav-settings':
      await expect(page.getByTestId('settings-session-facts')).toBeVisible();
      break;
    default:
      break;
  }
}

/** Signs in with the keyboard alone: focus, type, Enter. */
async function signInFromTheKeyboard(page: import('@playwright/test').Page) {
  await page.getByTestId('session-token-input').focus();
  await page.keyboard.type(ACCESS_TOKEN as string);
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Owner session' })).toBeVisible();
}

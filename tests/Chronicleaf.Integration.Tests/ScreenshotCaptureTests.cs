/// <summary>
/// A real HTTP listener that counts what reaches it, and nothing else.
/// </summary>
/// <remarks>
/// The design's oracle for the network scenarios: assert that blocked traffic never reached a sentinel
/// server, rather than asserting on what the code under test said about itself. It is bound to the
/// loopback address on an ephemeral port, it answers a 200 with a fixed body, and it counts every
/// request it receives - so "the far side received nothing" is a number this test measured.
/// <para>
/// It is not a page. Nothing in this suite navigates a browser, and no scenario using this listener
/// claims otherwise; it exists to be a destination that either is or is not contacted.
/// </para>
/// </remarks>
public sealed class CountingSentinel : IDisposable
{
    private readonly HttpListener _listener = new();
    private int _requests;

    public CountingSentinel()
    {
        Port = FreePort();
        Url = $"http://127.0.0.1:{Port}";
        Host = "127.0.0.1";

        _listener.Prefixes.Add($"http://127.0.0.1:{Port}/sentinal/");
        _listener.Start();

        _ = Task.Run(AcceptAsync);
    }

    /// <summary>The origin a scenario points a capture at.</summary>
    public string Url { get; }

    /// <summary>The address the listener is bound to.</summary>
    public string Host { get; }

    /// <summary>The port the listener is bound to.</summary>
    public int Port { get; }

    /// <summary>How many requests reached the far side.</summary>
    public int Requests => Volatile.Read(ref _requests);

    public void Dispose() => _listener.Close();

    private async Task AcceptAsync()
    {
        while (_listener.IsListening)
        {
            try
            {
                var context = await _listener.GetContextAsync();

                Interlocked.Increment(ref _requests);

                context.Response.StatusCode = 200;
                context.Response.Close();
            }
            catch (HttpListenerException)
            {
                // The listener was closed, which is how this loop ends.
                return;
            }
            catch (ObjectDisposedException)
            {
                return;
            }
        }
    }

    private static int FreePort()
    {
        using var probe = new System.Net.Sockets.TcpListener(System.Net.IPAddress.Loopback, 0);
        probe.Start();

        var port = ((System.Net.IPEndPoint)probe.LocalEndpoint).Port;
        probe.Stop();

        return port;
    }
}

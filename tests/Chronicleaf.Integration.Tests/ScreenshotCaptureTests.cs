    [Fact]
    public async Task Capture_001_Success_a_permitted_public_url_becomes_a_candidate_with_provenance_and_real_png_bytes()
    {
        var scenario = await ScenarioAsync("cap_001_success");
        await using var host = scenario.Host;
        using var owner = await OwnerClient.CreateAsync(host);

        var fixture = await CreateMilestoneAsync(owner, "首次可复现发布");
        host.Provider.AnswerWithPng(width: 1440, height: 900);

        var operationId = await RequestCaptureAsync(owner, fixture.MilestoneId, PublicUrl, ["desktop"], 0);
        await RunJobAsync(host, operationId);

        var candidates = await ReadCandidatesAsync(owner, fixture.MilestoneId);
        var candidate = Assert.Single(candidates);

        // The design's success clause: the candidate identifies the final URL, the capture time and the
        // viewport, with real PNG bytes behind it.
        Assert.Equal(PublicUrl, candidate.SourceUrl);
        Assert.Equal(PublicUrl, candidate.FinalUrl);
        Assert.Equal("desktop", candidate.Viewport);
        Assert.Equal(1440, candidate.Width);
        Assert.Equal(900, candidate.Height);
        Assert.Equal(fixture.ProjectId, candidate.ProjectId);
        Assert.Equal("succeeded", await ReadOperationStatusAsync(owner, operationId));

        // The bytes are real, stored by the delivered media store, and they are the bytes that were
        // handed in: the media record's own SHA-256 is compared with the digest computed independently
        // from the fixture PNG, so "the picture stored is the picture captured" is checked rather than
        // assumed.
        var stored = await ChronicleafPostgresFixture.ReadTextAsync(
            host.Database,
            $"SELECT sha256 FROM media WHERE id = '{candidate.MediaId}'");

        Assert.Equal(Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(TestPng.Create(1440, 900)))
            .ToLowerInvariant(), stored);

        // And they are readable through the delivered media route as a PNG of the stated size, which is
        // the only place in this repository that hands stored bytes back.
        using var image = await owner.GetAsync($"/api/media/{candidate.MediaId}");
        Assert.Equal(HttpStatusCode.OK, image.StatusCode);
        Assert.Equal("image/png", image.Content.Headers.ContentType?.MediaType);

        var served = await image.Content.ReadAsByteArrayAsync();
        Assert.Equal(1440u, ReadPngWidth(served));
        Assert.Equal(900u, ReadPngHeight(served));

        // A candidate is offered and nothing more. Every curation field is the constant this package
        // inserts, and the design's boundary is that capture does not select.
        Assert.Equal("candidate", candidate.Status);
        Assert.False(candidate.IsPrimary);
        Assert.Equal(string.Empty, candidate.Caption);
        Assert.Equal(1, candidate.Revision);

        // Nothing was appended to the evidence bundle. Capture does not attach a candidate to approved
        // evidence, and the bundle is still the one hand-written item the fixture created.
        Assert.Equal(1, await ChronicleafPostgresFixture.CountRowsAsync(host.Database, "evidence_items"));
    }


import { expect, test, type Page } from '@playwright/test';

/**
 * WEB-RESP-001/002/003/004/005/006 in a real browser, against the real
 * published application with a real PostgreSQL behind it.
 *
 * This suite runs in its own e2e group with its own disposable database
 * (see scripts/e2e.sh, suite 30): it creates projects by clicking, and a
 * project cannot be removed once it exists, so it reads its own
 * installation rather than the one suite 1 asserts empty. Every record
 * below is created by the same clicks an owner would make, with names
 * unique to this suite, and every claim is read back from the page. No
 * capture carries a credential, a token, a PAT or a session value.
 *
 * Viewports are set per test (360/720/960/1280px wide) over the single
 * chromium project the config names; media queries re-evaluate on
 * resize, so each claim reads the layout the owner would actually get.
 *
 * The setup token is generated by scripts/e2e.sh for this run and handed
 * to the fixtures through the environment. It is never written into this
 * file, never printed and never asserted on.
 */
const ACCESS_TOKEN = process.env.CHRONICLEAF_E2E_ACCESS_TOKEN;

test.beforeEach(async ({ page }) => {
  if (!ACCESS_TOKEN) {
    throw new Error(
      'CHRONICLEAF_E2E_ACCESS_TOKEN is not set. Run these fixtures through scripts/e2e.sh, which ' +
        'starts the published application with a real access token hash and a real database.',
    );
  }

  await page.context().clearCookies();
  await page.goto('/');
});

test('WEB-RESP-001: the top nav collapses behind an operable Menu disclosure at 360px', async ({
  page,
}) => {
  await signIn(page);
  await page.setViewportSize({ width: 360, height: 800 });

  const menu = page.getByTestId('nav-menu');
  await expect(menu).toBeVisible();
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  await expect(menu).toHaveAttribute('aria-controls', 'app-nav');
  await expect(page.getByTestId('nav-projects')).toBeHidden();

  await menu.click();
  await expect(menu).toHaveAttribute('aria-expanded', 'true');

  // The same six entries, as a vertical list.
  for (const entry of [
    'nav-projects',
    'nav-clients',
    'nav-timeline',
    'nav-operations',
    'nav-credentials',
    'nav-settings',
  ]) {
    await expect(page.getByTestId(entry)).toBeVisible();
  }
  await expect(page.getByTestId('nav-projects')).toHaveAttribute('aria-current', 'page');

  // Choosing an entry navigates and closes the list.
  await page.goto('/');
  await menu.click();
  await page.getByTestId('nav-operations').click();
  await expect(page.getByRole('heading', { name: 'Background jobs', exact: true })).toBeVisible();
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  await expect(page.getByTestId('nav-operations')).toHaveAttribute('aria-current', 'page');
});


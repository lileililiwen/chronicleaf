    [Fact]
    public async Task Capture_001_Boundary_one_failing_page_keeps_the_successes_and_records_the_failure()
    {
        var scenario = await ScenarioAsync("cap_001_partial");
        await using var host = scenario.Host;
        using var owner = await OwnerClient.CreateAsync(host);

        var fixture = await CreateMilestoneAsync(owner, "部分成功");

        // One URL at both viewports, and the desktop one does not load. This is the design's boundary
        // expressed in the design's own wire shape: a job is several page-captures, and one of them
        // failing is not the same event as all of them failing.
        host.Provider.AnswerWithViewportOf(
            request => request.Viewport.Name == "mobile",
            width: 390,
            height: 844,
            fullPage: false);
        host.Provider.FailWith(
            request => request.Viewport.Name == "desktop",
            () => new CaptureTimedOutException("The page did not load in time."));

        var operationId = await RequestCaptureAsync(owner, fixture.MilestoneId, PublicUrl, ["desktop", "mobile"], 0);
        await RunJobAsync(host, operationId);

        var candidates = await ReadCandidatesAsync(owner, fixture.MilestoneId);

        // The design's boundary clause: successful candidates and explicit failed-page results are
        // distinguishable. One candidate exists and the job succeeded, because a partial run is not a
        // failed run - and the failed page is visible as an absence with a named reason in the result
        // reference, not as a candidate pointing at a picture of an error page.
        var candidate = Assert.Single(candidates);
        Assert.Equal("mobile", candidate.Viewport);
        Assert.Equal("succeeded", await ReadOperationStatusAsync(owner, operationId));

        // The result reference counts the two kinds apart, which is how a client learns a page was
        // refused without reading the candidates and guessing.
        Assert.Equal(
            $"{ScreenshotCaptureService.CaptureOperationKind}:2:1:1",
            await ChronicleafPostgresFixture.ReadTextAsync(
                host.Database,
                $"SELECT result_ref FROM operations WHERE id = '{operationId}'"));
    }

    [Fact]
    public async Task Capture_001_Boundary_the_same_job_cannot_write_the_same_url_at_one_viewport_twice()
    {
        var scenario = await ScenarioAsync("cap_001_duplicate_tuple");
        await using var host = scenario.Host;
        using var owner = await OwnerClient.CreateAsync(host);

        var fixture = await CreateMilestoneAsync(owner, "重复的作业");
        host.Provider.AnswerWithPng(width: 1440, height: 900);

        var operationId = await RequestCaptureAsync(owner, fixture.MilestoneId, PublicUrl, ["desktop"], 0);
        await RunJobAsync(host, operationId);

        // Re-running the same operation by hand is what a queue redelivery looks like. The design's
        // tuple is the database's, not this service's: the second run's insert changes no row and is
        // told so, so the second picture is retired rather than stored and left orphaned.
        await using var scope = host.Services.CreateAsyncScope();
        var capture = scope.ServiceProvider.GetRequiredService<IScreenshotCaptureService>();

        // Nothing new was captured, so the job fails rather than committing a result reference that
        // names zero candidates - which would be indistinguishable from a job that never ran.
        var raised = await Assert.ThrowsAsync<OperationPermanentException>(
            () => capture.RunAsync(new OwnerScope(InstallationId, Guid.Empty), operationId));

        Assert.Equal(CapturePageError.Duplicate, raised.Message.Contains(CapturePageError.Duplicate, StringComparison.Ordinal)
            ? CapturePageError.Duplicate
            : raised.Message);
        Assert.Equal(1, await ChronicleafPostgresFixture.CountRowsAsync(host.Database, "screenshot_candidates"));

        // The second run's media was retired rather than left behind as a second servable picture.
        // Retirement in this repository is a status transition and not a deleted row - the delivered
        // media package keeps the record and releases the bytes - so the claim is about statuses: one
        // image is still servable and the duplicate is terminal. Counting rows here would have asserted
        // a deletion this package does not perform.
        Assert.Equal(1, await CountMediaInStatusAsync(host.Database, MediaStatus.Ready));
        Assert.Equal(1, await CountMediaInStatusAsync(host.Database, MediaStatus.Deleted));

        // And the real consequence, on the real files: the kept candidate's picture is still readable
        // through the delivered media route, and the retired one is not.
        var kept = Assert.Single(await ReadCandidatesAsync(owner, fixture.MilestoneId));

        using var served = await owner.GetAsync($"/api/media/{kept.MediaId:D}");
        Assert.Equal(HttpStatusCode.OK, served.StatusCode);
    }


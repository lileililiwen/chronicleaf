using Chronicleaf.Application.Milestones;
using Chronicleaf.Core;

// The Core record is addressed as an alias throughout this file: inside the Chronicleaf.Application.Media
// namespace the bare identifier `Media` resolves to the namespace itself, and a name that means two
// things in the same file is a name that will eventually mean the wrong one.
using MediaRecord = Chronicleaf.Core.Media;

namespace Chronicleaf.Application.Media;

/// <summary>
/// The media use cases (LOCAL-MEDIA-STORAGE-001/002), and the design's <c>IMediaStore</c> shape.
/// </summary>
/// <remarks>
/// <para>
/// This is the facade over the storage provider, and it is Chronicleaf's own: the provider's
/// <c>IObjectStorage</c> is adopted in Infrastructure and is deliberately not redeclared here. That
/// split is what keeps three properties in one place instead of three. The key is generated by the
/// implementation and is not a parameter of any method below, so no caller can choose where bytes
/// land. Every method takes an <see cref="OwnerScope"/> rather than a bare id, so a lookup for
/// another installation's media is a not-found and not a read. And the two-phase sequence in
/// <see cref="PutAsync"/> - stage, verify, promote, then register - is one method's body rather than
/// a convention each caller re-implements.
/// </para>
/// <para>
/// Nothing here is asynchronous on the caller's behalf. <see cref="RetireAsync"/> stops a record
/// being served before it releases any bytes, and <see cref="PurgeUnreferencedAsync"/> is the
/// reconciliation the design calls for; neither invents a background runner of its own, because
/// scheduling belongs to the jobs package and this package does not get to decide what runs when.
/// </para>
/// </remarks>
public interface IMediaStore
{
    /// <summary>
    /// Stores one image for <paramref name="owner"/>'s project and returns its reference.
    /// </summary>
    /// <remarks>
    /// The sequence, in this order and with nothing skipped:
    /// <list type="number">
    /// <item>
    /// The bytes are read once under <see cref="MediaLimits.MaximumByteLength"/>, so an oversized
    /// body is refused before any key exists and nothing is written.
    /// </item>
    /// <item>
    /// They are decoded - signature, first chunk, dimensions and terminator - and their SHA-256 is
    /// computed. A body that is not an accepted image is refused here, with nothing on disk.
    /// </item>
    /// <item>
    /// The bytes are written under a server-generated <em>pending</em> key and the write is verified
    /// against the provider's own metadata.
    /// </item>
    /// <item>
    /// They are promoted to the <em>ready</em> key, the promotion is verified the same way, and the
    /// pending object is released. A missing release is success, not a failure.
    /// </item>
    /// <item>
    /// Only then is the record registered, in one unit of work with its audit row, and only with
    /// <see cref="MediaStatus.Ready"/>.
    /// </item>
    /// </list>
    /// Any failure in steps 3 to 5 releases whatever this call wrote and registers nothing, so a
    /// failed call leaves no <c>ready</c> row and no published orphan. A step that fails after the
    /// pending object is gone leaves a pending row that is never served and is reconcilable.
    /// </remarks>
    /// <exception cref="MediaNotFoundException">The project is absent or in another scope (404).</exception>
    /// <exception cref="UnsupportedMediaTypeException">The bytes are not an accepted image (415).</exception>
    /// <exception cref="MediaTooLargeException">The body is over the byte limit (413).</exception>
    /// <exception cref="MediaImageTooLargeException">The decoded image is over the pixel limit (422).</exception>
    /// <exception cref="MediaStorageUnavailableException">The provider could not complete the write (503).</exception>
    Task<MediaRef> PutAsync(OwnerScope owner, PutMediaInput input, CancellationToken cancellationToken = default);

    /// <summary>
    /// Opens the bytes of one image for its own scope, or answers nothing at all.
    /// </summary>
    /// <remarks>
    /// A not-found is returned for an unknown id, for an id in another scope, for a record that is
    /// not <see cref="MediaStatus.Ready"/> - which is what makes a pending, retained or deleted
    /// record unservable without any of them needing a special case - and for a stored key that
    /// resolves outside MediaRoot. The caller never learns which of those it was.
    /// </remarks>
    /// <exception cref="MediaNotFoundException">There is nothing here this caller may read (404).</exception>
    /// <exception cref="MediaStorageUnavailableException">The provider could not serve the read (503).</exception>
    Task<MediaContent> OpenAsync(OwnerScope owner, Guid mediaId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Stops an image being served and then releases its bytes, refusing while anything references
    /// it.
    /// </summary>
    /// <remarks>
    /// The reference check happens before anything is written, so a refused call has changed nothing
    /// and the bytes are still there. A reference is whatever
    /// <see cref="IMediaReferenceChecker"/> reports; this package does not own the references and
    /// does not pretend to. A record that is already retired is reported as it stands rather than
    /// retried.
    /// </remarks>
    /// <exception cref="MediaNotFoundException">The id is absent, out of scope, or already retired (404).</exception>
    /// <exception cref="MediaInUseException">Something still references it (409 <c>media_in_use</c>).</exception>
    Task<RetireMediaResult> RetireAsync(OwnerScope owner, Guid mediaId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Reconciles staged objects that never became a published record, and reports what it released.
    /// </summary>
    /// <remarks>
    /// The design's reconciler, exposed and unscheduled: it sweeps objects under a pending key that
    /// are older than a cutoff and are referenced by no live record, which is the only state an
    /// interrupted upload can leave behind. It is a method rather than a hosted service on purpose -
    /// what runs it, and how often, is the jobs package's decision and not this one's - and it is
    /// idempotent, so a caller that runs it twice releases nothing the second time.
    /// </remarks>
    Task<int> PurgeUnreferencedAsync(DateTimeOffset stagedBefore, int limit, CancellationToken cancellationToken = default);
}

/// <summary>
/// The Chronicleaf-owned side of the media table (LOCAL-MEDIA-STORAGE-002).
/// </summary>
/// <remarks>
/// Separate from <see cref="IMediaStore"/> because this is the only part that knows about rows. The
/// store above composes it with a storage provider; a test or a later package can read stored state
/// without acquiring a provider, and a row is never reachable by any path that also resolves a key.
/// <para>
/// Every method is scoped, and the scope is in the WHERE clause rather than in a filter applied
/// afterwards, so a lookup by id can only ever return a record inside the caller's own installation.
/// </para>
/// </remarks>
public interface IMediaRepository
{
    /// <summary>Reads one record in a scope, or <c>null</c> when it is absent or out of scope.</summary>
    Task<MediaRecord?> FindAsync(Guid scopeId, Guid mediaId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Inserts a record. Returns <c>false</c> when another writer inserted the same id first, which
    /// is a collision and not a success.
    /// </summary>
    Task<bool> InsertAsync(MediaRecord media, CancellationToken cancellationToken = default);

    /// <summary>
    /// Moves a record from one status to another, and to no other, while it still holds
    /// <paramref name="expectedStatus"/>. The status is never a parameter of a caller: the
    /// compare-and-set is what stops a stale writer from promoting or reviving a record.
    /// </summary>
    /// <returns>How many rows changed. Zero means the record moved on without this call.</returns>
    Task<int> TransitionStatusAsync(
        Guid scopeId,
        Guid mediaId,
        string expectedStatus,
        string newStatus,
        DateTimeOffset changedAt,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Reads staged records - ones still named by a pending key - that were created before
    /// <paramref name="stagedBefore"/>, oldest first, bounded by <paramref name="limit"/>. These are
    /// the only rows a purge may consider, and whether a candidate is still referenced is decided by
    /// <see cref="IMediaReferenceChecker"/> rather than here.
    /// </summary>
    Task<IReadOnlyList<MediaRecord>> ListStalePendingAsync(
        DateTimeOffset stagedBefore,
        int limit,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Reads the record that names a storage key, in any status, or <c>null</c>. This is what lets a
    /// purge tell a still-tracked staged object from an orphan on disk, which are indistinguishable
    /// from the filesystem alone.
    /// </summary>
    Task<MediaRecord?> FindByStorageKeyAsync(string storageKey, CancellationToken cancellationToken = default);
}

/// <summary>
/// Reports whether anything still references a stored image (LOCAL-MEDIA-STORAGE-002).
/// </summary>
/// <remarks>
/// <para>
/// References are not this package's to own. An evidence bundle linking a screenshot to a milestone
/// is a later package's table with its own lifecycle, and a reference check written here against a
/// table that does not exist yet would be a guess at someone else's schema that the moment they
/// arrive would be wrong. So the decision is an interface with a seam, registered once here and
/// replaced by whoever owns the references.
/// </para>
/// <para>
/// The registered default reports that nothing is referenced, and that default is honest rather than
/// permissive: it is the truth in a Community installation with no evidence bundles, and a
/// deployment that does have them gets a different implementation rather than a weakened one. The
/// 409 <c>media_in_use</c> path is exercised by the tests through this seam, so the mechanism is
/// proven before the table behind it exists.
/// </para>
/// <para>
/// Implementations answer a question about one id and never return a reference itself, so an
/// implementation cannot leak a caller's evidence by being asked whether something points at a row.
/// </para>
/// </remarks>
public interface IMediaReferenceChecker
{
    /// <summary>True when at least one stored record still points at this media.</summary>
    Task<bool> IsReferencedAsync(Guid mediaId, CancellationToken cancellationToken = default);
}

/// <summary>
/// The registered reference check for a Community installation that has no evidence bundles yet.
/// </summary>
/// <remarks>
/// It answers "nothing references this", which is the truth in an installation where no package has
/// created a reference table, and it is replaced - not extended - by whichever package owns
/// references. It is not a permissive stub that swallows the question: it is a real answer, and the
/// 409 <c>media_in_use</c> path is exercised through this same seam by the tests, so the mechanism is
/// proven before the table behind it exists.
/// <para>
/// It holds no state and reaches no database, which is what makes it obvious that nothing is being
/// faked: there is no reference store for it to consult, so it cannot accidentally appear to know
/// about one.
/// </para>
/// </remarks>
public sealed class NoMediaReferenceChecker : IMediaReferenceChecker
{
    public Task<bool> IsReferencedAsync(Guid mediaId, CancellationToken cancellationToken = default) =>
        Task.FromResult(false);
}

/// <summary>
/// Generates the identity of a new media record (LOCAL-MEDIA-STORAGE-001).
/// </summary>
/// <remarks>
/// An interface rather than a direct <c>Guid.NewGuid()</c> so a test can state the identity it
/// expects to find in a key, on disk and in a row, instead of reading it back from whatever the
/// process happened to produce. Production uses <see cref="NewMediaIdSource"/>, which is the only
/// implementation that exists in this repository - the seam is for determinism, not for a pluggable
/// identity policy.
/// </remarks>
public interface IMediaIdSource
{
    /// <summary>The id the next upload will be registered under.</summary>
    Guid NextMediaId();
}

/// <summary>The production identity source: a fresh v4 UUID per upload.</summary>
public sealed class NewMediaIdSource : IMediaIdSource
{
    public Guid NextMediaId() => Guid.NewGuid();
}

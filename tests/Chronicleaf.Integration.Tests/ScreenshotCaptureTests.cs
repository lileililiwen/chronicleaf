    [Fact]
    public void An_allowance_matches_one_exact_origin_and_pins_one_address()
    {
        var allowance = new CaptureLocalAllowance(
            "http://localhost:4173",
            System.Net.IPAddress.Parse("192.168.1.50"),
            Clock.AddMinutes(30));

        var mode = CaptureDeploymentMode.Community;
        var loopback = new[] { System.Net.IPAddress.Loopback };

        // The exact origin, the pinned address, inside the window: permitted.
        Assert.True(CaptureUrlPolicy.EvaluateAddress(
            new Uri("http://localhost:4173/"),
            [System.Net.IPAddress.Parse("192.168.1.50")],
            mode,
            [allowance],
            Clock).Allowed);

        // A different port is a different origin. A prefix match would have permitted this, which is
        // exactly the class of bug the control exists to stop.
        Assert.Equal(
            CaptureUrlPolicy.ReasonAllowanceOriginMismatch,
            CaptureUrlPolicy.EvaluateAddress(
                new Uri("http://localhost:4174/"),
                [System.Net.IPAddress.Parse("192.168.1.50")],
                mode,
                [allowance],
                Clock).Reason);

        // A name that merely ends with the permitted host is not that host.
        Assert.Equal(
            CaptureUrlPolicy.ReasonAllowanceOriginMismatch,
            CaptureUrlPolicy.EvaluateAddress(
                new Uri("http://localhost.attacker.example:4173/"),
                [System.Net.IPAddress.Parse("192.168.1.50")],
                mode,
                [allowance],
                Clock).Reason);

        // The same origin resolving somewhere else is refused, and it says so with the word that tells
        // an operator the address moved rather than the rule.
        Assert.Equal(
            CaptureUrlPolicy.ReasonAllowanceAddressMismatch,
            CaptureUrlPolicy.EvaluateAddress(
                new Uri("http://localhost:4173/"),
                [System.Net.IPAddress.Parse("192.168.9.9")],
                mode,
                [allowance],
                Clock).Reason);

        // An expired allowance refuses exactly like a lapsed one, with its own word.
        Assert.Equal(
            CaptureUrlPolicy.ReasonAllowanceExpired,
            CaptureUrlPolicy.EvaluateAddress(
                new Uri("http://localhost:4173/"),
                [System.Net.IPAddress.Parse("192.168.1.50")],
                mode,
                [allowance],
                Clock.AddHours(1)).Reason);

        // The instant the window closes is the boundary: one tick before is allowed, the tick itself is
        // not. An allowance with a closed window must not linger.
        Assert.True(CaptureUrlPolicy.EvaluateAddress(
            new Uri("http://localhost:4173/"),
            [System.Net.IPAddress.Parse("192.168.1.50")],
            mode,
            [allowance],
            allowance.ExpiresAt.AddTicks(-1)).Allowed);

        Assert.Equal(
            CaptureUrlPolicy.ReasonAllowanceExpired,
            CaptureUrlPolicy.EvaluateAddress(
                new Uri("http://localhost:4173/"),
                [System.Net.IPAddress.Parse("192.168.1.50")],
                mode,
                [allowance],
                allowance.ExpiresAt).Reason);

        _ = loopback;
    }


    [Fact]
    public void The_egress_gate_makes_the_same_decision_the_proxy_would_and_connects_to_nothing_when_it_refuses()
    {
        // The gate function the proxy calls once per connection, exercised directly with a real
        // listener behind it. The listener is the sentinel: a decision that permitted the connection
        // would produce a request count of one, so "denied" here is a claim about bytes that did not
        // move rather than a claim about a return value.
        using var sentinel = new CountingSentinel();

        var gate = new CaptureEgressGate(new FixedTimeProvider(Clock), NullLogger<CaptureEgressGate>.Instance);
        var policy = CaptureEgressPolicy.Default(CaptureDeploymentMode.Community, Clock);

        var denied = gate.Evaluate(
            $"{sentinel.Host}:{sentinel.Port}",
            [System.Net.IPAddress.Loopback],
            policy);

        Assert.False(denied.Allowed);
        Assert.Equal(CaptureUrlPolicy.ReasonAllowanceOriginMismatch, denied.Reason);
        Assert.Empty(denied.Addresses);

        // Nothing was dialled as a consequence of the denial, and the listener confirms it: an attempt
        // made now would be counted.
        Assert.Equal(0, sentinel.Requests);

        // A public address with the same gate is permitted, and the same listener is still untouched -
        // so the difference is the decision, not the socket.
        var allowed = gate.Evaluate(
            $"{sentinel.Host}:{sentinel.Port}",
            [System.Net.IPAddress.Parse("93.184.216.34")],
            policy);

        Assert.True(allowed.Allowed, allowed.Reason);
        Assert.Equal(0, sentinel.Requests);
    }


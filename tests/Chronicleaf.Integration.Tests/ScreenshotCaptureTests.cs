    // SCREENSHOT-CAPTURE-002 Failure: a blocked destination never reaches the far side.
    // ===========================================================================================

    [Fact]
    public async Task Capture_002_Failure_a_blocked_destination_is_refused_and_never_dialled()
    {
        var sentinel = new CountingSentinel();
        using (sentinel)
        {
            var scenario = await ScenarioAsync("cap_002_blocked");
            await using var host = scenario.Host;
            using var owner = await OwnerClient.CreateAsync(host);

            var fixture = await CreateMilestoneAsync(owner, "被阻止的目标");
            host.Provider.AnswerWithPng();

            // A listener this scenario owns, on the loopback address the policy refuses by default. If
            // the refusal were advisory this would be a real connection and a real count of one.
            var blockedUrl = $"{sentinel.Url}/private";

            // The policy decision itself, for the addresses that destination resolves to.
            var decision = CaptureUrlPolicy.EvaluateAddress(
                new Uri(blockedUrl),
                [System.Net.IPAddress.Loopback],
                CaptureDeploymentMode.Community,
                allowances: null,
                Clock);

            Assert.False(decision.Allowed);
            Assert.Equal(CaptureUrlPolicy.ReasonAllowanceOriginMismatch, decision.Reason);

            // The same destination through the real request route: 403, no job, and no candidate.
            var refused = await PostCaptureAsync(owner, fixture.MilestoneId, blockedUrl, ["desktop"], 0);

            Assert.Equal(HttpStatusCode.Forbidden, refused.StatusCode);
            Assert.Equal("capture_target_blocked", await ReadCodeAsync(refused));

            // The sentinel's own words: nothing arrived.
            Assert.Equal(0, sentinel.Requests);
            Assert.Empty(await ReadCandidatesAsync(owner, fixture.MilestoneId));
            Assert.Equal(0, await ChronicleafPostgresFixture.CountRowsAsync(host.Database, "operations"));

            // The refusal message quotes no host, no address and no range.
            var body = await refused.Content.ReadAsStringAsync();
            Assert.DoesNotContain("127.0.0.1", body, StringComparison.Ordinal);
            Assert.DoesNotContain("localhost", body, StringComparison.Ordinal);
        }
    }

    [Fact]
    public async Task Capture_002_Failure_a_private_address_written_in_ipv6_spelling_is_refused_before_anything_is_dialed()
    {
        // The one that matters most, because it is a real hole rather than a missing test: a URL whose
        // host is an IPv4 private address inside an IPv6 envelope. The policy judges an address it is
        // given, and judging ::ffff:10.0.0.5 with the IPv6 rules finds nothing to refuse - the first
        // byte is 0x00, so it is neither unique-local nor link-local - and returns "public page". The
        // request would have been accepted, a job created, and a browser pointed at a host on the
        // owner's own network. This is the assertion that would have failed before the fix.
        var scenario = await ScenarioAsync("cap_002_v4_mapped");
        await using var host = scenario.Host;
        using var owner = await OwnerClient.CreateAsync(host);

        var fixture = await CreateMilestoneAsync(owner, "IPv4 映射地址");
        host.Provider.AnswerWithPng();

        var mapped = "http://[::ffff:10.0.0.5]/admin";
        var metadata = "http://[::ffff:169.254.169.254]/latest/meta-data/";

        // The decision itself, for both addresses, in the form the code under test uses.
        Assert.False(CaptureUrlPolicy.IsPubliclyRoutable(System.Net.IPAddress.Parse("::ffff:10.0.0.5")));
        Assert.True(CaptureUrlPolicy.IsMetadataAddress(System.Net.IPAddress.Parse("::ffff:169.254.169.254")));

        Assert.Equal(
            CaptureUrlPolicy.ReasonAllowanceOriginMismatch,
            CaptureUrlPolicy.EvaluateAddress(
                new Uri(mapped),
                [System.Net.IPAddress.Parse("::ffff:10.0.0.5")],
                CaptureDeploymentMode.Community,
                allowances: null,
                Clock).Reason);

        Assert.Equal(
            CaptureUrlPolicy.ReasonMetadataService,
            CaptureUrlPolicy.EvaluateAddress(
                new Uri(metadata),
                [System.Net.IPAddress.Parse("::ffff:169.254.169.254")],
                CaptureDeploymentMode.Community,
                allowances: null,
                Clock).Reason);

        // And the consequence through the real route: refused, with the destination's own code, and
        // refused before a job exists - so there is nothing for a worker to pick up and dial later.
        var refused = await PostCaptureAsync(owner, fixture.MilestoneId, mapped, ["desktop"], 0);

        Assert.Equal(HttpStatusCode.Forbidden, refused.StatusCode);
        Assert.Equal(CaptureError.TargetBlocked, await ReadCodeAsync(refused));

        var refusedMetadata = await PostCaptureAsync(owner, fixture.MilestoneId, metadata, ["desktop"], 0);

        Assert.Equal(HttpStatusCode.Forbidden, refusedMetadata.StatusCode);
        Assert.Equal(CaptureError.TargetBlocked, await ReadCodeAsync(refusedMetadata));

        // No job, no candidate, and no page was ever asked of the browser.
        Assert.Equal(0, await ChronicleafPostgresFixture.CountRowsAsync(host.Database, "operations"));
        Assert.Empty(await ReadCandidatesAsync(owner, fixture.MilestoneId));
        Assert.Empty(host.Provider.Requests);
    }

    [Fact]
    public async Task Capture_002_Failure_the_job_re_checks_the_policy_and_never_asks_the_browser_about_a_blocked_literal()
    {
        // "Wired at request time" and "wired at page time" are two different claims, and this is the
        // second one. A request row is edited outside this package - the service documents that as the
        // only way it happens - so the destination the job is about to photograph is not the one the
        // request route judged. The job has to consult the policy again, and the observable that
        // matters is that the browser was never asked: the page outcome is a refusal rather than a
        // capture attempt that happened to fail.
        var provider = new RecordingScreenshotProvider(new FixedTimeProvider(Clock));
        var scenario = await ScenarioAsync("cap_002_page_time_recheck", provider);
        await using var host = scenario.Host;
        using var owner = await OwnerClient.CreateAsync(host);

        var fixture = await CreateMilestoneAsync(owner, "作业时复查");
        provider.AnswerWithPng();

        var operationId = await RequestCaptureAsync(owner, fixture.MilestoneId, PublicUrl, ["desktop"], 0);

        // A permitted public URL at request time, replaced by a private literal before the job runs.
        var edited = await ChronicleafPostgresFixture.ExecuteAsync(
            host.Database,
            $"""UPDATE capture_requests SET urls = '["http://192.168.1.1/"]'::jsonb WHERE operation_id = '{operationId}'""");

        Assert.Equal(1, edited);

        await RunJobAsync(host, operationId);

        // The policy was consulted at page time and the page was refused, not attempted.
        Assert.Empty(provider.Requests);
        Assert.Empty(await ReadCandidatesAsync(owner, fixture.MilestoneId));
        Assert.Equal(0, await ChronicleafPostgresFixture.CountRowsAsync(host.Database, "screenshot_candidates"));
        Assert.Equal(0, await ChronicleafPostgresFixture.CountRowsAsync(host.Database, "media"));

        // Every page failed, so the job fails with the page's own reason and commits no result
        // reference naming zero candidates.
        Assert.Equal("failed", await ReadOperationStatusAsync(owner, operationId));
        Assert.Equal(
            CapturePageError.TargetBlocked,
            await ChronicleafPostgresFixture.ReadTextAsync(
                host.Database,
                $"SELECT error_code FROM operations WHERE id = '{operationId}'"));
        Assert.Null(await ChronicleafPostgresFixture.ReadTextAsync(
            host.Database,
            $"SELECT result_ref FROM operations WHERE id = '{operationId}'"));
    }

    [Theory]
    // Metadata is refused in every mode, at every expiry, and an allowance cannot change it.
    [InlineData("http://169.254.169.254/latest/meta-data/", CaptureUrlPolicy.ReasonMetadataService)]
    [InlineData("http://[fd00:ec2::254]/latest/meta-data/", CaptureUrlPolicy.ReasonMetadataService)]
    // A redirect or subresource to a private address is refused too: the same rule, applied again.
    [InlineData("http://10.0.0.5/admin", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    [InlineData("http://192.168.1.1/", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    [InlineData("http://172.16.4.4/", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    [InlineData("http://127.0.0.1:8080/", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    // Carrier-grade NAT, which a single-tenant install is quite likely to photograph by accident.
    [InlineData("http://100.64.0.1/", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    // 127.0.0.0/8, not just 127.0.0.1. A check written as "the address equals 127.0.0.1" refuses
    // exactly one of the addresses a loopback can be, and this host has others: 127.0.0.53 is the
    // systemd-resolved stub resolver on most Linux distributions and answers on it.
    [InlineData("http://127.0.0.53:8080/", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    [InlineData("http://127.1.2.3:8080/", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    // The same private, loopback and metadata addresses written in IPv6 spelling. These are one
    // address, not two: ::ffff:a.b.c.d is an IPv4 address in a 16-byte envelope, and judging it with
    // the IPv6 rules finds nothing to refuse (its first byte is 0x00, so it is neither unique-local nor
    // link-local) and permits a host on the owner's own network as a public page. The metadata one is
    // the serious case: a capture that reached it would be handed an instance's credentials.
    [InlineData("http://[::ffff:10.0.0.5]/admin", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    [InlineData("http://[::ffff:127.0.0.53]:8080/", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    [InlineData("http://[::ffff:169.254.169.254]/latest/meta-data/", CaptureUrlPolicy.ReasonMetadataService)]
    [InlineData("http://[::ffff:192.168.1.1]/", CaptureUrlPolicy.ReasonAllowanceOriginMismatch)]
    public void Capture_002_Failure_a_local_or_metadata_destination_is_refused(string url, string expectedReason)
    {
        var decision = CaptureUrlPolicy.EvaluateAddress(
            new Uri(url),
            [Resolve(url)],
            CaptureDeploymentMode.Community,
            allowances: null,
            Clock);

        Assert.False(decision.Allowed);
        Assert.Equal(expectedReason, decision.Reason);
    }


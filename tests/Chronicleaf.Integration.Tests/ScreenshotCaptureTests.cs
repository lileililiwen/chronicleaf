    /// </remarks>
    private static int CountBrowserProcesses()
    {
        try
        {
            return Directory
                .GetFiles("/proc")
                .Count(entry => File.Exists(Path.Combine(entry, "comm")) && IsBrowserName(ReadComm(entry)));
        }
        catch (IOException)
        {
            return 0;
        }
    }

    private static string ReadComm(string procEntry)
    {
        try
        {
            return File.ReadAllText(Path.Combine(procEntry, "comm")).Trim();
        }
        catch (IOException)
        {
            return string.Empty;
        }
    }


/// <summary>
/// The screenshot-capture scenarios, one per stated outcome, against a real disposable PostgreSQL and
/// the real API host (SCREENSHOT-CAPTURE-001/002).
/// </summary>
/// <remarks>
/// <para>
/// <b>What is real here.</b> The database is a genuine PostgreSQL server started from a pinned image,
/// migrated with the committed migrations, and every assertion about state reads it back. The API
/// host, the owner session boundary, the antiforgery value, the operation queue, the Hangfire server,
/// the workers, the stores, the delivered media store and both routes are the production ones. A
/// scenario that runs a job runs it through the delivered outbox dispatcher and the delivered worker;
/// nothing calls the service directly to make a result appear.
/// </para>
/// <para>
/// <b>What is substituted, and why.</b> Only <see cref="IScreenshotProvider"/>, which is this
/// package's declared seam in exactly the shape the delivered <c>IGitEvidenceSource</c> was. The
/// production registration resolves the sandbox-backed Playwright provider; the test host replaces that
/// one registration with a recording provider and changes nothing else - not the URL policy, not the
/// bounds, not the media limits, not the candidate table or its unique constraint.
/// </para>
/// <para>
/// <b>There is no real screenshot anywhere in this file, and nothing here claims there is.</b> The
/// production backend needs an unprivileged network namespace and owner-based firewall rules. This
/// host has neither - no effective capabilities, no root, and a user namespace that cannot be created
/// - so the production provider answers <c>capture_sandbox_unavailable</c> here, and that refusal is
/// asserted directly by
/// <see cref="Capture_002_Failure_a_capture_in_this_environment_refuses_with_sandbox_unavailable_and_starts_no_browser"/>,
/// which also proves no browser process was launched. The PNGs the recording provider hands back are
/// generated by <see cref="TestPng"/> for the purpose of exercising what happens after a picture
/// exists: the media write, the candidate row, the dimension and digest checks. A scenario asserting
/// on one of those is asserting on the storage path, never on capture working.
/// </para>
/// <para>
/// <b>What the egress enforcement is and is not proven as.</b> The URL policy is pure, synchronous
/// code and is tested directly here, case by case, with no socket and no browser. The kernel half -
/// the firewall rules and the proxy that make a browser unable to route around the policy - cannot run
/// on this host at all, because the mechanism is precisely what is missing. The gate function the
/// proxy calls per connection is exercised against a real listener, so the sentinel claim "the far side
/// received nothing" is proven for the decision function; the kernel enforcement above it is recorded
/// as unproven on this host rather than asserted.
/// </para>
/// </remarks>
[Collection(ChronicleafPostgresCollection.Name)]
public sealed class ScreenshotCaptureTests(ChronicleafPostgresFixture postgres)

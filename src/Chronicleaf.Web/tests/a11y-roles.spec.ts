/** Signs in with the keyboard alone: focus, type, Enter. */
async function signIn(page: Page) {
  await page.getByTestId('session-token-input').focus();
  await page.keyboard.type(ACCESS_TOKEN as string);
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Owner session' })).toBeVisible();
}

/** Creates a project with one confirmed milestone (manual records confirm on save). */
async function createProjectWithConfirmedMilestone(page: Page, name: string): Promise<string> {
  await signIn(page);

  await page.goto('/projects/new');
  await page.getByTestId('project-name-input').fill(name);
  await page.getByTestId('project-description-input').fill('Created by the a11y-roles suite.');
  await page.getByTestId('project-save').click();

  await expect(page).toHaveURL(/\/projects\/[0-9a-f-]{36}$/);
  const projectId = new URL(page.url()).pathname.split('/').filter(Boolean)[1] ?? '';

  await page.getByTestId('milestone-new').click();
  await page.getByTestId('milestone-title-input').fill('A11y roles milestone');
  await page.getByTestId('milestone-type-input').selectOption('feature');
  await page.getByTestId('milestone-occurred-at-input').fill('2026-09-28T09:30');
  await page.getByTestId('milestone-limitations-input').fill('No multi-currency yet.');
  await page.getByTestId('milestone-next-steps-input').fill('Add the reconciliation report.');
  await page.getByTestId('milestone-save').click();

  await expect(page).toHaveURL(new RegExp(`/projects/${projectId}$`));
  await expect(page.getByTestId('milestone-status').first()).toHaveText('confirmed');
  return projectId;
}

/**
 * Asserts the heading order inside the single <main id="main"> landmark:
 * exactly one h1, and no heading steps up more than one level.
 * A null path asserts against the current page (after in-test navigation).
 */
async function assertHeadingOrder(page: Page, path: string | null, expected: { h1: number }) {
  if (path !== null) {
    await page.goto(path);
  }

  const headings = await page.evaluate(() => {
    const main = document.querySelector('main#main');
    const scope = main ?? document;
    return Array.from(scope.querySelectorAll('h1, h2, h3, h4, h5, h6')).map((element) => ({
      level: Number(element.tagName.slice(1)),
      text: (element.textContent ?? '').trim().slice(0, 80),
    }));
  });

  const h1Count = headings.filter((heading) => heading.level === 1).length;
  expect(h1Count, `exactly one h1 (found: ${JSON.stringify(headings)})`).toBe(expected.h1);

  for (let index = 1; index < headings.length; index += 1) {
    const previous = headings[index - 1];
    const current = headings[index];
    expect(
      current.level - previous.level,
      `no skipped level between "${previous.text}" (h${previous.level}) and "${current.text}" (h${current.level})`,
    ).toBeLessThanOrEqual(1);
  }
}

/** Asserts every aria-pressed chip on the page sits inside a role=group. */
async function assertChipsGrouped(page: Page) {
  const ungrouped = await page.evaluate(() => {
    const offenders: string[] = [];
    for (const chip of Array.from(document.querySelectorAll('button[aria-pressed]'))) {
      if (chip.closest('[role="group"]') === null) {
        offenders.push(chip.getAttribute('data-testid') ?? chip.textContent?.trim() ?? '?');
      }
    }
    return offenders;
  });
  expect(ungrouped, 'every aria-pressed chip sits in a role=group').toEqual([]);
}

/** Asserts every color-modifier badge carries a Status: accessible name plus visible text. */
async function assertBadgesNamed(page: Page) {
  const badges = await page.evaluate(() => {
    return Array.from(document.querySelectorAll('.badge--ok, .badge--pending, .badge--muted')).map(
      (element) => ({
        label: element.getAttribute('aria-label'),
        text: (element.textContent ?? '').trim(),
      }),
    );
  });
  expect(badges.length, 'at least one modifier badge on the page').toBeGreaterThan(0);
  for (const badge of badges) {
    expect(badge.label, `badge "${badge.text}" carries a Status: name`).toMatch(/^Status: /);
    expect(badge.text.length, 'badge keeps its visible status word').toBeGreaterThan(0);
  }
}

/** Asserts every visible control matching the selector measures at least 40px tall. */
async function assertTouchFloor(page: Page, selector: string, scope: string) {
  const heights = await page.evaluate((sel) => {
    const measured: number[] = [];
    for (const element of Array.from(document.querySelectorAll(sel))) {
      const box = (element as HTMLElement).getBoundingClientRect();
      const visible = box.width > 0 && box.height > 0 && (element as HTMLElement).offsetParent !== null;
      if (visible) {
        measured.push(box.height);
      }
    }
    return measured;
  }, selector);

  expect(heights.length, `at least one visible ${selector} (${scope})`).toBeGreaterThan(0);
  for (const height of heights) {
    expect(height, `${selector} in ${scope} meets the 40px floor`).toBeGreaterThanOrEqual(40);
  }
}

    /// <summary>
    /// How many browser processes are running right now, counted from the real process table.
    /// </summary>
    /// <remarks>
    /// A process count rather than a flag the provider sets, because the property the refusal protects
    /// is not "the provider reported that it did nothing" but "no browser exists". This host has the

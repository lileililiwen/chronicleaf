/// <summary>
/// Hosts the real application with the real queue running, against a real disposable PostgreSQL, with
/// a recording screenshot provider in place of the browser and nothing else faked.
/// </summary>
/// <remarks>
/// <para>
/// The host is the delivered <c>WebApplicationFactory</c> pattern: the connection string arrives
/// through the same configuration key production reads, the access configuration through its own
/// keys. The Hangfire storage, the server, the workers, the outbox dispatcher, the stores, the media
/// store, the operation queue and the routes are all the production ones.
/// </para>
/// <para>
/// <b>The only substitution is the browser, and it is the package's own declared seam.</b>
/// <see cref="IScreenshotProvider"/> is a DI seam exactly as the delivered <c>IGitEvidenceSource</c>
/// was, and the production registration resolves the sandbox-backed Playwright provider. This host
/// removes that registration and adds a <see cref="RecordingScreenshotProvider"/>. It does not
/// reconfigure the supervisor, does not touch the URL policy, does not substitute a store and does
/// not disable the media limits - so a scenario exercises this package's real bounds, its real
/// candidate writes, its real uniqueness constraint and its real media writes, and only the act of
/// photographing a page is the test's.
/// </para>
/// <para>
/// <b>Why a recording provider and not a browser.</b> The production backend needs an unprivileged
/// network namespace and owner-based firewall rules, which this host does not have; the production
/// provider answers <c>capture_sandbox_unavailable</c> on such a host, which is the correct behaviour
/// and is asserted directly in a scenario of its own. A scenario that needs to exercise what happens
/// after a picture exists substitutes the seam, and every PNG it hands back is a fixed fixture
/// generated by the test itself - never presented as something a browser produced.
/// </para>
/// <para>
/// The automated dispatch loop is off and the polling is fast, exactly as the github-evidence and
/// background-jobs hosts do it: the loop is the seam between "the request committed" and "the queue
/// knows", and a scenario has to be able to place a capture on a chosen side of it. A scenario that
/// needs the loop runs <see cref="DispatchAsync"/>, which is the loop's own body called by hand.
/// </para>
/// </remarks>
public sealed class CaptureApiHost : WebApplicationFactory<Program>
{
    private readonly string _connectionString;
    private readonly TimeProvider _clock;
    private readonly RecordingScreenshotProvider _provider;
    private readonly string? _mediaRoot;
    private readonly LogCapture _logs = new();
    private readonly bool _substituteProvider;

    private readonly CaptureDeploymentMode _mode;

    private CaptureApiHost(
        string connectionString,
        TimeProvider clock,
        RecordingScreenshotProvider provider,
        string? mediaRoot,
        CaptureDeploymentMode mode,
        bool substituteProvider)
    {
        _connectionString = connectionString;
        _clock = clock;
        _provider = provider;
        _mediaRoot = mediaRoot;
        _mode = mode;
        _substituteProvider = substituteProvider;
    }

    /// <summary>The connection string this host was started with, for the assertions that read the database.</summary>
    public string Database => _connectionString;

    /// <summary>The media root this run created, for the assertions that read stored bytes.</summary>
    public string? MediaRoot => _mediaRoot;

    /// <summary>The browser seam the application is really using, for the assertions about what it asked for.</summary>
    public RecordingScreenshotProvider Provider => _provider;

    /// <summary>What the server logged, for the assertions that a refusal said why.</summary>
    public LogCapture Logs => _logs;

    public static CaptureApiHost Start(
        string connectionString,
        TimeProvider clock,
        RecordingScreenshotProvider provider,
        string? mediaRoot = null,
        CaptureDeploymentMode mode = CaptureDeploymentMode.Community) =>
        new(connectionString, clock, provider, mediaRoot, mode, substituteProvider: true);

    /// <summary>
    /// A host whose production <see cref="IScreenshotProvider"/> is left in place.
    /// </summary>
    /// <remarks>
    /// This is the only way a scenario can assert anything about the real browser's behaviour, because
    /// the real browser's behaviour on a host without a sandbox is to refuse. A host that substituted
    /// the seam could not show that at all, so the flag exists to keep one honest scenario possible.
    /// </remarks>
    public static CaptureApiHost WithProductionProvider(
        string connectionString,
        TimeProvider clock,
        string? mediaRoot = null,
        CaptureDeploymentMode mode = CaptureDeploymentMode.Community) =>
        new(connectionString, clock, new RecordingScreenshotProvider(clock), mediaRoot, mode, substituteProvider: false);

    protected override void ConfigureWebHost(IWebHostBuilder builder)
    {
        builder.UseSetting(ChronicleafConnection.SettingName, _connectionString);
        builder.UseSetting(AccessSettings.AccessTokenHashSettingName, OwnerClient.AccessTokenHash);
        builder.UseSetting(AccessSettings.PublicOriginSettingName, OwnerClient.PublicOrigin);
        builder.UseEnvironment("Production");

        // The dispatch loop runs only when a scenario asks it to, so a capture can be staged either
        // side of the seam between "the request committed" and "the queue knows".
        builder.UseSetting($"{OperationQueueOptions.SectionName}:Enabled", "false");

        // A poll interval, not a behaviour: the queue, the workers and the claiming are production's.
        builder.UseSetting($"{OperationQueueOptions.SectionName}:SchedulePollingInterval", "00:00:00.200");
        builder.UseSetting($"{OperationQueueOptions.SectionName}:HeartbeatInterval", "00:00:05");

        // The deployment mode is the one production setting a scenario varies, because it is the input
        // the design requires to be real: Hosted refuses a local allowance whatever is configured, and
        // that is a different answer rather than a different comment.
        builder.UseSetting($"{CaptureSandboxSettings.SectionName}:DeploymentMode", _mode.ToString());

        if (_mediaRoot is not null)
        {
            builder.UseSetting(MediaSettings.MediaRootSettingName, _mediaRoot);
        }

        // The server's own log is captured so a scenario can read what the server said when the
        // envelope alone is opaque. It is the same capture the other hosts use.
        builder.ConfigureLogging(logging =>
        {
            logging.SetMinimumLevel(LogLevel.Trace);
            logging.AddProvider(_logs);
        });

        builder.ConfigureServices(services =>
        {
            services.RemoveAll<TimeProvider>();
            services.AddSingleton(_clock);

            if (_substituteProvider)
            {
                // The one substitution: the browser seam. Everything behind it - the bounds, the
                // policy, the media write, the candidate row and the uniqueness constraint - is
                // production's.
                services.RemoveAll<IScreenshotProvider>();
                services.AddSingleton<IScreenshotProvider>(_provider);
            }
        });
    }

    /// <summary>
    /// Runs one real outbox dispatch pass: the delivered dispatcher hands each pending event to the
    /// registered handler, which enqueues a real job through the real <c>IJobDispatcher</c>.
    /// </summary>
    public async Task<IReadOnlyList<OutboxDispatchResult>> DispatchAsync(CancellationToken cancellationToken = default)
    {
        using var scope = Services.CreateScope();
        var dispatcher = scope.ServiceProvider.GetRequiredService<IOutboxDispatcher>();
        var stamper = scope.ServiceProvider.GetRequiredService<IOutboxDispatchStamper>();
        var clock = scope.ServiceProvider.GetRequiredService<TimeProvider>();

        var results = await dispatcher.DispatchPendingAsync(100, cancellationToken);

        foreach (var result in results)
        {
            if (result.Outcome == OutboxDispatchOutcome.Handled)
            {
                await stamper.TryMarkDispatchedAsync(result.EventId, clock.GetUtcNow(), cancellationToken);
            }
        }

        return results;
    }
}

/// <summary>
/// A screenshot provider that records what it was asked for and answers from a script the test wrote.
/// </summary>
/// <remarks>
/// <para>
/// This is the package's declared seam, used the way the delivered github-evidence host uses its fake
/// GitHub: the real service, the real queue, the real media store and the real database, with only the
/// browser replaced. It is a <see cref="IScreenshotProvider"/>, so it cannot reach the credential vault,
/// a connection string or the media root - which is the same structural property the production
/// provider has.
/// </para>
/// <para>
/// <b>The bytes it hands back are a fixture, and they are labelled as one.</b> Nothing in this
/// environment can navigate a page, so there is no real screenshot anywhere in this suite; the PNGs are
/// generated by <see cref="TestPng"/> for the purpose of exercising what happens after a picture
/// exists - the media write, the candidate row, the dimension and digest checks. A scenario that
/// asserts on one is asserting on the storage path, never on capture itself, and the suite's own
/// documentation says so where a reader could otherwise be misled.
/// </para>
/// <para>
/// A rule that never matches raises rather than answering, so a scenario that expected a capture and
/// did not get one fails with the reason the provider was given rather than silently.
/// </para>
/// </remarks>
public sealed class RecordingScreenshotProvider(TimeProvider clock) : IScreenshotProvider
{
    private readonly List<CaptureRequest> _requests = [];
    private readonly List<(Func<CaptureRequest, bool> Match, Func<CaptureRequest, Task<CaptureResult>> Answer)> _rules = [];
    private readonly object _gate = new();

    /// <summary>Every request the service asked for, in order.</summary>
    public IReadOnlyList<CaptureRequest> Requests
    {
        get
        {
            lock (_gate)
            {
                return [.. _requests];
            }
        }
    }

    /// <summary>
    /// Answers every request that matches with a fixed PNG of the given dimensions.
    /// </summary>
    /// <param name="width">The picture's pixel width, which is also what the service's bounds see.</param>
    /// <param name="height">The picture's pixel height.</param>
    /// <param name="finalUrl">
    /// Where the page "ended up". Defaults to the requested URL, so a scenario that does not care
    /// about a redirect does not have to say so once per rule.
    /// </param>
    public RecordingScreenshotProvider AnswerWithPng(
        int width = 1440,
        int height = 900,
        Uri? finalUrl = null)
    {
        Func<CaptureRequest, bool> matches = _ => true;

        lock (_gate)
        {
            _rules.Add((matches, request => Task.FromResult(BuildPng(request, width, height, finalUrl))));
        }

        return this;
    }

    /// <summary>
    /// Answers matching requests with exactly these bytes, whatever they are.
    /// </summary>
    /// <remarks>
    /// The seam that lets a scenario drive the media store's own refusal - a truncated image has the
    /// right signature and the right header and is still not an image, so the delivered store rejects
    /// it at its type check and the service has to fail the candidate. That is the design's "a media
    /// write failure fails candidate creation" path, reached through the real store rather than a
    /// substituted one.
    /// </remarks>
    public RecordingScreenshotProvider AnswerWithBytes(
        Func<CaptureRequest, bool> matches,
        Func<CaptureRequest, byte[]> bytes)
    {
        lock (_gate)
        {
            _rules.Add((matches, request =>
            {
                var payload = bytes(request);

                return Task.FromResult(new CaptureResult(
                    new MemoryStream(payload, writable: false),
                    Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(payload)).ToLowerInvariant(),
                    payload.LongLength,
                    8,
                    8,
                    request.Url,
                    clock.GetUtcNow()));
            }));
        }

        return this;
    }

    /// <summary>Answers a request with bytes whose declared dimensions the service will judge.</summary>
    public RecordingScreenshotProvider AnswerWithViewportOf(
        Func<CaptureRequest, bool> matches,
        int width,
        int height,
        bool fullPage)
    {
        lock (_gate)
        {
            _rules.Add((matches, request =>
            {
                var payload = TestPng.Create(width, height);

                return Task.FromResult(new CaptureResult(
                    new MemoryStream(payload, writable: false),
                    Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(payload)).ToLowerInvariant(),
                    payload.LongLength,
                    width,
                    height,
                    request.Url,
                    clock.GetUtcNow()));
            }));
        }

        return this;
    }

    /// <summary>Answers requests whose URL contains <paramref name="urlFragment"/> with a fixed PNG.</summary>
    public RecordingScreenshotProvider AnswerWithPngFor(
        string urlFragment,
        int width = 1440,
        int height = 900)
    {
        Func<CaptureRequest, bool> matches = request =>
            request.Url.AbsoluteUri.Contains(urlFragment, StringComparison.Ordinal);

        lock (_gate)
        {
            _rules.Add((matches, request => Task.FromResult(BuildPng(request, width, height, null))));
        }

        return this;
    }

    /// <summary>Raises <paramref name="failure"/> for every matching request.</summary>
    public RecordingScreenshotProvider FailWith(
        Func<CaptureRequest, bool> matches,
        Func<Exception> failure)
    {
        lock (_gate)
        {
            _rules.Add((matches, _ => Task.FromException<CaptureResult>(failure())));
        }

        return this;
    }

    /// <summary>Forgets every rule and every recorded request, so a scenario can re-script between phases.</summary>
    public void Reset()
    {
        lock (_gate)
        {
            _rules.Clear();
            _requests.Clear();
        }
    }

    /// <inheritdoc />
    public Task<CaptureResult> CaptureAsync(CaptureRequest request, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);

        Func<CaptureRequest, Task<CaptureResult>>? answer;

        lock (_gate)
        {
            _requests.Add(request);

            // The last matching rule wins, so a scenario can add a specific rule after a general one
            // without having to remove it - which is what makes a one-page-out-of-three scenario
            // readable.
            var rule = _rules.LastOrDefault(candidate => candidate.Match(request));
            answer = rule.Answer;
        }

        if (answer is null)
        {
            // A request the script did not expect. Answering with something anyway would let a scenario
            // pass on a capture that never happened.
            throw new CapturePageNotRenderedException(
                "The recording provider was asked for a page no rule answered.");
        }

        return answer(request);
    }

    private CaptureResult BuildPng(CaptureRequest request, int width, int height, Uri? finalUrl)
    {
        // A test-generated PNG, not a browser's output. Its dimensions are the ones the caller asked
        // for because the service's 40-megapixel bound is asserted against them.
        var bytes = TestPng.Create(width, height);

        return new CaptureResult(
            new MemoryStream(bytes, writable: false),
            Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(bytes)).ToLowerInvariant(),
            bytes.LongLength,
            width,
            height,
            finalUrl ?? request.Url,
            clock.GetUtcNow());
    }
}
